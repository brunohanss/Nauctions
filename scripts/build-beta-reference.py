"""Build the app and addon reference from the archived Normal Horde page-chart data."""
from collections import defaultdict
from datetime import date
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "data/foreverdb-normal-horde/normal-horde-daily.jsonl"


def lua_string(value):
    return '"' + ''.join(chr(b) if 32 <= b < 127 and b not in (34, 92) else f"\\{b:03d}" for b in value.encode("utf-8")) + '"'


def build():
    raw = SOURCE.read_bytes()
    rows = [json.loads(line) for line in raw.splitlines()]
    grouped = defaultdict(list)
    origin = date(2026, 10, 3)
    for row in rows:
        assert row["realm"] == "Classic Beta PvE 2" and row["house"] == "Horde"
        grouped[row["item_id"]].append(row)
    items = []
    for item_id, entries in sorted(grouped.items()):
        entries.sort(key=lambda r: r["date"])
        assert len({r["date"] for r in entries}) == len(entries)
        items.append({"id": item_id, "name": entries[0]["name"] or f"Item {item_id}",
                      "variants_combined": entries[0]["variants_combined"],
                      "points": [[(date.fromisoformat(r["date"]) - origin).days,
                                  r["min_buyout_copper"], r["median_buyout_copper"], r["listed_quantity"]] for r in entries]})
    data = {"schema_version": 1, "source": "https://foreverdb.net", "source_realm": "Classic Beta PvE 2",
            "house": "Horde", "region": None, "build": None, "beta_started_at": None,
            "reference_date": origin.isoformat(), "source_updated_at": rows[0]["source_updated_at"],
            "source_sha256": hashlib.sha256(raw).hexdigest(), "daily_rows": len(rows),
            "attribution": {"text": "Data from ForeverDB.net", "url": "https://foreverdb.net"}, "items": items}
    target = ROOT / "assets/beta-normal-horde.json"
    target.write_text(json.dumps(data, ensure_ascii=False, separators=(",", ":")) + "\n", encoding="utf-8")
    lua = ['-- Generated by scripts/build-beta-reference.py. Daily asking-price summaries, not live scans.',
           '-- Data from ForeverDB.net: https://foreverdb.net (keep visible attribution).',
           'local _, ADB = ...',
           'ADB.betaReference = {schema_version=1, reference_date="2026-10-03", source="https://foreverdb.net", source_realm="Classic Beta PvE 2", house="Horde", items={']
    for item in items:
        points = ','.join('{' + ','.join('false' if v is None else str(v) for v in p) + '}' for p in item["points"])
        lua.append(f'[{item["id"]}]={{name={lua_string(item["name"])},variants_combined={str(item["variants_combined"]).lower()},points={{{points}}}}},')
    lua.append('}}')
    (ROOT / "addon/AuctionDB/NauctionsBeta.lua").write_text('\n'.join(lua) + '\n', encoding="utf-8")
    print(f"Built {len(items)} items and {len(rows)} daily observations; reference origin is not a reset time.")


if __name__ == "__main__":
    build()
